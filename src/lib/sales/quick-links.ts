/**
 * Quick links: everything you need to reach a lead, on the lead, as one-tap links. Nothing to search for.
 *
 *   Where they posted   the post itself, and the author's profile on that platform
 *   Written in the post emails, phones, WhatsApp links and websites the poster wrote, copied exactly
 *   The person          saved handles, plus profiles research verified in what it read
 *   The company         website, emails and phones from their own site, WhatsApp, social pages, address on a map
 *   People there        decision makers first, each with LinkedIn and email
 *
 * Every link says where it came from, so you know how much to trust it. A guessed email is labelled as a guess.
 * A link is only ever built from data we hold; nothing here is generated by AI.
 */
