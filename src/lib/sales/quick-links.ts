const enc = encodeURIComponent;
const v = (f: { v?: unknown } | undefined | null): string | null => {
  const x = f?.v;
  return x === null || x === undefined || String(x).trim() === "" ? null : String(x).trim();
};

// ------------------------------------------------------------------ pure helpers (tested)

/** The author's profile on the platform, built only from the platform's own URL patterns. */
export function authorProfile(url: string | null | undefined, author: string | null | undefined): QuickLink | null {
  const p = platformOf(url);
  if (!p || !url) return null;
  const a = (author ?? "").trim().replace(/^\/?u\//i, "").replace(/^@/, "");
  if (p.key === "reddit" && /^[\w-]{3,40}$/.test(a)) {
    return { kind: "profile", label: `u/${a} on Reddit`, value: null, href: `https://www.reddit.com/user/${a}`, source: "platform" };
  }
  if (p.key === "hn" && /^[\w-]{2,40}$/.test(a)) {
    return { kind: "profile", label: `${a} on Hacker News`, value: "Profile may list an email", href: `https://news.ycombinator.com/user?id=${a}`, source: "platform" };
  }
  try {
    const u = new URL(url);
    if (p.key === "x") {
      const h = u.pathname.split("/").filter(Boolean)[0];
      if (h && /^\w{1,30}$/.test(h) && !["i", "search", "home", "explore"].includes(h)) return { kind: "profile", label: `@${h} on X`, value: null, href: `https://x.com/${h}`, source: "platform" };
    }
    if (p.key === "linkedin_post") {
      const m = u.pathname.match(/^\/posts\/([a-z0-9-]{3,100})_/i);
      if (m) return { kind: "linkedin", label: "Author's LinkedIn", value: m[1], href: `https://www.linkedin.com/in/${m[1]}`, source: "platform" };
    }
  } catch {
    /* not a URL */
  }
  return null;
}

const PLATFORM_HOSTS = /(^|\.)(reddit\.com|redd\.it|ycombinator\.com|upwork\.com|freelancer\.com|linkedin\.com|x\.com|twitter\.com|imgur\.com|i\.redd\.it|youtube\.com|youtu\.be|google\.com|bit\.ly)$/i;
const JUNK_EMAIL = /@(example\.(com|org)|email\.com|domain\.com|test\.com|yourdomain\.com|sentry\.io)$/i;

/** Contacts the poster wrote in the post, copied exactly. Phones only with a + or 00 prefix (never dates or prices). */
export function textContacts(text: string | null | undefined): QuickLink[] {
  const t = text ?? "";
  const out: QuickLink[] = [];
  for (const e of new Set((t.match(/[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}/gi) ?? []).map((x) => x.toLowerCase()))) {
    if (!JUNK_EMAIL.test(e)) out.push({ kind: "email", label: "Email", value: e, href: `mailto:${e}`, source: "post", copy: e });
  }
  for (const w of new Set(t.match(/(?:https?:\/\/)?(?:wa\.me|api\.whatsapp\.com\/send\?phone=)\/?\+?\d{8,15}/gi) ?? [])) {
    const d = waDigitsPure(w.replace(/\D+/g, " ").trim().split(" ").pop());
    if (d) out.push({ kind: "whatsapp", label: "WhatsApp", value: `+${d}`, href: `https://wa.me/${d}`, source: "post", copy: `+${d}` });
  }
  for (const ph of new Set(t.match(/(?:\+|\b00)\d[\d\s().-]{7,16}\d/g) ?? [])) {
    const digits = ph.replace(/\D/g, "").replace(/^00/, "");
    if (digits.length < 8 || digits.length > 15) continue;
    if (out.some((x) => x.kind === "whatsapp" && x.value === `+${digits}`)) continue;
    out.push({ kind: "call", label: "Phone", value: `+${digits}`, href: `tel:+${digits}`, source: "post", copy: `+${digits}` });
    out.push({ kind: "whatsapp", label: "WhatsApp (if they use it)", value: `+${digits}`, href: `https://wa.me/${digits}`, source: "post" });
  }
  for (const raw of new Set(t.match(/https?:\/\/[^\s<>()"']+/gi) ?? [])) {
    const url = raw.replace(/[.,;:!?)\]]+$/, "");
    try {
      const host = new URL(url).hostname.replace(/^www\./, "");
      if (PLATFORM_HOSTS.test(host) || /wa\.me|whatsapp\.com/.test(host)) continue;
      if (/\.(png|jpe?g|gif|webp|svg|mp4|pdf)$/i.test(url)) continue;
      out.push({ kind: "website", label: host, value: null, href: url, source: "post" });
    } catch {
      /* skip */
    }
  }
  return out.slice(0, 10);
}

/** "linkedin: https://...; instagram: https://..." from research, as links. */
export function socialLinks(s: string | null, source: LinkSource): QuickLink[] {
  if (!s) return [];
  const out: QuickLink[] = [];
  for (const part of s.split(/;\s*/)) {
    const m = part.match(/^\s*([a-z]+)\s*:\s*(https?:\/\/\S+)\s*$/i);
    if (!m) continue;
    const name = m[1].toLowerCase();
    const pretty: Record<string, string> = { linkedin: "LinkedIn page", instagram: "Instagram", facebook: "Facebook", twitter: "X", x: "X", youtube: "YouTube", tiktok: "TikTok", github: "GitHub", telegram: "Telegram" };
    out.push({ kind: name === "linkedin" ? "linkedin" : "social", label: pretty[name] ?? name, value: null, href: m[2], source });
  }
  return out;
}

function phoneLinks(raw: string | null, source: LinkSource, whatsappToo: boolean): QuickLink[] {
  if (!raw) return [];
  const out: QuickLink[] = [];
  for (const p of raw.split(/[,|;]\s*/).map((x) => x.trim()).filter(Boolean).slice(0, 3)) {
    const tel = p.replace(/[^\d+]/g, "");
    if (tel.replace(/\D/g, "").length < 7) continue;
    out.push({ kind: "call", label: "Phone", value: p, href: `tel:${tel}`, source, copy: p });
    const d = whatsappToo ? waDigitsPure(p) : null;
    if (d) out.push({ kind: "whatsapp", label: "WhatsApp", value: p, href: `https://wa.me/${d}`, source });
  }
  return out;
}

function emailLinks(raw: string | null, source: LinkSource, label = "Email"): QuickLink[] {
  if (!raw) return [];
  return raw
    .split(/[,;\s]+/)
    .map((x) => x.trim().toLowerCase())
    .filter((x) => /^[^@\s]+@[^@\s]+\.[a-z]{2,}$/.test(x))
    .slice(0, 4)
    .map((e) => ({ kind: "email" as const, label, value: e, href: `mailto:${e}`, source, copy: e }));
}

function websiteLink(url: string | null): QuickLink | null {
  if (!url) return null;
  const href = /^https?:\/\//i.test(url) ? url : `https://${url}`;
  try {
    return { kind: "website", label: "Website", value: new URL(href).hostname.replace(/^www\./, ""), href, source: "saved" };
  } catch {
    return null;
  }
}

function linkedinUrl(v: string): string {
  return /^https?:/i.test(v) ? v : `https://www.linkedin.com/in/${v.replace(/^in\//, "")}`;
}

/** Drops links that already appear in an earlier group, and empty groups. */
export function dedupe(groups: LinkGroup[]): LinkGroup[] {
  const seen = new Set<string>();
  const key = (l: QuickLink) => l.href.toLowerCase().replace(/^https?:\/\/(www\.)?/, "").replace(/\/+$/, "");
  return groups
    .map((g) => ({ ...g, links: g.links.filter((l) => (seen.has(key(l)) ? false : (seen.add(key(l)), true))) }))
    .filter((g) => g.links.length || g.note);
}

// ------------------------------------------------------------------ from the database

interface PersonLinks {
  id: number;
  full_name: string;
  title: string | null;
  company_id: number | null;
  emails: string[];
  phones: string[];
  linkedin: string | null;
  instagram: string | null;
  twitter: string | null;
  is_decision_maker: boolean | null;
  enrichment: Enrichment;
}
interface CompanyLinks {
  id: number;
  name: string;
  website: string | null;
  address: string | null;
  enrichment: Enrichment;
  enriched_at: string | null;
}

function personGroup(p: PersonLinks, title?: string): LinkGroup {
  const e = p.enrichment ?? {};
  const links: QuickLink[] = [];
  for (const ph of p.phones ?? []) links.push(...phoneLinks(ph, "saved", true));
  for (const em of p.emails ?? []) links.push(...emailLinks(em, "saved"));
  if (p.linkedin) links.push({ kind: "linkedin", label: "LinkedIn", value: null, href: linkedinUrl(p.linkedin), source: "saved" });
  if (p.instagram) links.push({ kind: "social", label: "Instagram", value: `@${p.instagram}`, href: `https://www.instagram.com/${p.instagram.replace(/^@/, "")}`, source: "saved" });
  if (p.twitter) links.push({ kind: "social", label: "X", value: `@${p.twitter}`, href: `https://x.com/${p.twitter.replace(/^@/, "")}`, source: "saved" });
  if (!p.emails?.length) links.push(...emailLinks(v(e.email_guess), "guess", "Likely email"));
  links.push(...phoneLinks(v(e.phone_found), "research", true));
  for (const u of (v(e.other_profiles) ?? "").match(/https?:\/\/[^\s,;]+/g) ?? []) {
    try {
      links.push({ kind: "social", label: new URL(u).hostname.replace(/^www\./, ""), value: null, href: u, source: "research" });
    } catch {
      /* skip */
    }
  }
  const role = [p.title, p.is_decision_maker ? "decides" : null].filter(Boolean).join(", ");
  return { title: title ?? `${p.full_name}${role ? ` · ${role}` : ""}`, links };
}

function companyGroup(c: CompanyLinks): LinkGroup {
  const e = c.enrichment ?? {};
  const links: QuickLink[] = [];
  const w = websiteLink(c.website);
  if (w) links.push(w);
  links.push(...emailLinks(v(e.generic_email), "website", "General email"));
  links.push(...emailLinks(v(e.public_emails), "website"));
  const wa = v(e.whatsapp_number);
  if (wa) {
    const d = waDigitsPure(wa.replace(/^https?:\/\/wa\.me\//, ""));
    if (d) links.push({ kind: "whatsapp", label: "WhatsApp", value: `+${d}`, href: `https://wa.me/${d}`, source: "website", copy: `+${d}` });
  }
  links.push(...phoneLinks(v(e.public_phones), "website", false));
  links.push(...socialLinks(v(e.social_profiles), "website"));
  const addr = v(e.address)?.split(" | ")[0] ?? null;
  if (addr) links.push({ kind: "map", label: "Address", value: addr, href: `https://www.google.com/maps/search/?api=1&query=${enc(addr)}`, source: "website", copy: addr });
  const note = c.enriched_at ? (links.length <= 1 ? "Research found no public contact details on their website." : null) : "Research has not run yet: tap Research and the links appear here in about a minute.";
  return { title: c.name, note, links };
}

const PERSON_SQL = `select id, full_name, title, company_id, emails, phones, linkedin, instagram, twitter, is_decision_maker, enrichment from sales_people`;
const COMPANY_SQL = `select id, name, website, null as address, enrichment, enriched_at from sales_companies`;

/** Quick links for many radar leads at once (one round of queries, for the radar page). */
export async function radarQuickLinks(ids: number[]): Promise<Record<number, LinkGroup[]>> {
  if (!ids.length) return {};
  const items = await q<{ id: number; url: string | null; author: string | null; title: string; body: string | null; company_id: number | null; person_id: number | null }>(
    "select id, url, author, title, body, company_id, person_id from sales_radar_items where id = any($1)",
    [ids],
  );
  const companyIds = [...new Set(items.map((i) => i.company_id).filter((x): x is number => !!x))];
  const companies = companyIds.length ? await q<CompanyLinks>(`${COMPANY_SQL} where id = any($1)`, [companyIds]) : [];
  const people = companyIds.length
    ? await q<PersonLinks>(`${PERSON_SQL} where company_id = any($1) order by (is_decision_maker is true) desc, (linkedin is not null) desc, id`, [companyIds])
    : [];
  const out: Record<number, LinkGroup[]> = {};
  for (const it of items) {
    const groups: LinkGroup[] = [];
    const p = platformOf(it.url);
    const posted: QuickLink[] = [];
    if (it.url && /^https?:/.test(it.url)) posted.push({ kind: "post", label: p?.replyable ? `The post on ${p.name}` : "Where it was found", value: null, href: it.url, source: "platform" });
    if (it.url?.startsWith("mail:")) posted.push({ kind: "post", label: "The alert email in Gmail", value: null, href: `https://mail.google.com/mail/u/0/#all/${it.url.slice(5)}`, source: "platform" });
    const author = authorProfile(it.url, it.author);
    if (author) posted.push(author);
    groups.push({ title: "Where they posted", links: posted });
    const written = textContacts(`${it.title}\n${it.body ?? ""}`);
    if (written.length) groups.push({ title: "Written in their post", links: written });
    const contact = it.person_id ? people.find((x) => x.id === it.person_id) : null;
    if (contact && !isHandle(contact.full_name)) groups.push(personGroup(contact));
    const co = it.company_id ? companies.find((c) => c.id === it.company_id) : null;
    if (co) {
      groups.push(companyGroup(co));
      for (const person of people.filter((x) => x.company_id === co.id && x.id !== it.person_id).slice(0, 4)) groups.push(personGroup(person));
    } else {
      groups.push({ title: "The company", note: "This lead does not name a company yet. Tap Research and type the company or website if you know it.", links: [] });
    }
    out[it.id] = dedupe(groups);
  }
  return out;
}

/** Quick links for a deal: the contact, where the lead came from, the company, other people, the referrer. */
export async function dealQuickLinks(dealId: number): Promise<LinkGroup[]> {
  const d = (await q<{ id: number; person_id: number | null; company_id: number | null; referrer_id: number | null; intermediary_id: number | null; radar_item_id: number | null; source_detail: string | null }>(
    "select id, person_id, company_id, referrer_id, intermediary_id, radar_item_id, source_detail from sales_deals where id = $1",
    [dealId],
  ))[0];
  if (!d) return [];
  const groups: LinkGroup[] = [];
  const ids = [d.person_id, d.referrer_id, d.intermediary_id].filter((x): x is number => !!x);
  const named = ids.length ? await q<PersonLinks>(`${PERSON_SQL} where id = any($1)`, [ids]) : [];
  const main = named.find((x) => x.id === d.person_id);
  if (main && !isHandle(main.full_name)) groups.push(personGroup(main));
  if (d.radar_item_id) {
    const rq = await radarQuickLinks([d.radar_item_id]);
    for (const g of rq[d.radar_item_id] ?? []) if (g.title === "Where they posted" || g.title === "Written in their post") groups.push(g);
  } else if (d.source_detail && /^https?:\/\//.test(d.source_detail)) {
    groups.push({ title: "Where this lead came from", links: [{ kind: "post", label: platformOf(d.source_detail)?.name ?? "Source", value: null, href: d.source_detail, source: "saved" }] });
  }
  if (d.company_id) {
    const co = (await q<CompanyLinks>(`${COMPANY_SQL} where id = $1`, [d.company_id]))[0];
    if (co) groups.push(companyGroup(co));
    const others = await q<PersonLinks>(
      `${PERSON_SQL} where company_id = $1 and id <> all($2::int[]) order by (is_decision_maker is true) desc, (linkedin is not null) desc, id limit 4`,
      [d.company_id, ids.length ? ids : [0]],
    );
    for (const o of others) groups.push(personGroup(o));
  }
  const ref = named.find((x) => x.id === d.referrer_id);
  if (ref) groups.push(personGroup(ref, `${ref.full_name} · referred you`));
  const mid = named.find((x) => x.id === d.intermediary_id);
  if (mid) groups.push(personGroup(mid, `${mid.full_name} · intermediary`));
  return dedupe(groups);
}
